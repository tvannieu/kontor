check_only=0
[ "${1:-}" = "--check" ] && check_only=1
drift=0

emit() {  # emit <repo> <kind>
  local repo="$1" kind="$2" target="$HOME/$1/crush.json" want
  [ -d "$HOME/$repo" ] || { printf '  %-22s skipped (no such directory)\n' "$repo"; return; }
  if [ "$kind" = local ]; then
    local ro=no; for r in "${READONLY[@]}"; do [ "$r" = "$repo" ] && ro=yes; done
    want=$(local_cfg "$ro")
  else
    want=$(hosted_cfg)
  fi
  if [ -f "$target" ] && [ "$(cat "$target")" = "$want" ]; then
    printf '  %-22s up to date (%s)\n' "$repo" "$kind"; return
  fi
  drift=1
  if [ "$check_only" = 1 ]; then
    printf '  %-22s DRIFTED (%s)\n' "$repo" "$kind"; return
  fi
  printf '%s\n' "$want" > "$target"
  ignore_crush_json "$repo"
  printf '  %-22s written (%s)\n' "$repo" "$kind"
}

# ⚠️ qwen3-vl reasons on every turn and the OpenAI-compatible endpoint ignores
# "think": false — reasoning arrives in a separate field either way. What matters
# is that max_tokens is large enough to cover the reasoning AND the answer: with
# max_tokens 20 the content came back EMPTY and the call looked broken. The
# per-model default_max_tokens below (8192 / 4096) is the real safeguard.
#
# crush.json is machinery, not documentation: it is an output of this script, which
# is itself versioned in the manifest's canonical branch. Its history would never be read, and in a repo that
# is later shared with co-authors — drei Forschungszweigen — a personal
# tooling config naming an OpenRouter account is awkward to have committed.
# So every branch ignores it, decided once here rather than thirteen times separately.
# (Suggested by a sibling branch, 12.09.2026.)
ignore_crush_json() {
  local gi="$HOME/$1/.gitignore"
  [ -d "$HOME/$1/.git" ] || return 0
  if [ -f "$gi" ] && grep -qx 'crush.json' "$gi"; then return 0; fi
  [ -f "$gi" ] && [ -n "$(tail -c1 "$gi")" ] && printf '\n' >> "$gi"
  printf '\n# Crush-Konfiguration: generiert von tools/distribute_crush_config.sh.\n# Maschinerie, keine Dokumentation — nicht committen, nicht von Hand editieren.\ncrush.json\n' >> "$gi"
}

for r in "${LOCAL_FIRST[@]}"; do emit "$r" local;  done
for r in "${HOSTED[@]}";     do emit "$r" hosted; done

# Keep the wrapper's sandbox list in step with the classification above.
if [ "$check_only" = 0 ]; then
  mkdir -p "$(dirname "$BRANCH_LIST")"
  printf '%s\n' "${LOCAL_FIRST[@]}" > "$BRANCH_LIST"
  printf '  %-22s written (%d branches)\n' "$(basename "$BRANCH_LIST")" "${#LOCAL_FIRST[@]}"
fi

if [ "$check_only" = 1 ]; then
  [ "$drift" = 0 ] && echo "all crush configs match" || {
    echo "drift found — run without --check to overwrite" >&2; exit 1; }
fi
