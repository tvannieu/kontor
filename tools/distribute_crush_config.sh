# Distribute per-branch crush.json across the Kontor.
#
#   ./distribute_crush_config.sh          write the configs
#   ./distribute_crush_config.sh --check  report drift only, change nothing (exit 1 on drift)
#
# Parallel to distribute_manifest.sh. Thomas directs it; a session may run it.
# Never edit a branch's crush.json by hand — it is overwritten without warning.
#
# crush.json cannot carry a comment (the schema sets additionalProperties:false),
# so the "generated" marker lives in the provider's display name, where Crush shows it.

set -euo pipefail

# ---------------------------------------------------------------- configuration
# The classification is instance data and lives outside this repository.
# LOCAL_FIRST : the local model is the default; a hosted one is one keystroke away
# HOSTED      : a hosted model is the default
# READONLY    : the agent may read but not write in these branches
CONF="${KONTOR_CONF:-$HOME/.config/kontor/branches.conf}"
[ -r "$CONF" ] || { echo "no config at $CONF (see tools/kontor.conf.example)" >&2; exit 2; }
. "$CONF"
: "${LOCAL_FIRST:?}" "${HOSTED:?}" "${KONTOR_ROOT:?}"
READONLY=("${READONLY[@]:-}")

# The wrapper reads this to decide which branches default to local.
BRANCH_LIST="$HOME/.config/crush/local-first-branches"

